"""Embeds HomeNX-Loader.nro into the menu as a byte array.
Usage: python3 tools/embed_loader.py <HomeNX-Loader.nro> <out .inc>"""
import sys

data = open(sys.argv[1], "rb").read()
assert data[0x10:0x14] == b"NRO0", "not an .nro"
lines = []
for i in range(0, len(data), 24):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
with open(sys.argv[2], "w", newline="\n") as out:
    out.write("// Generated by tools/embed_loader.py from HomeNX-Loader.nro. Do not edit.\n")
    out.write(f"static const unsigned char kLoaderNroData[{len(data)}] = {{\n")
    out.write("\n".join(lines))
    out.write("\n};\n")
print(f"embedded {len(data)} bytes")
